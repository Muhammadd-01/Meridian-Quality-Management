export const ENTITY_BY_KEY = Object.fromEntries(ENTITY_LIST.map(e => [e.key, e]));

/** Recordable label for one record, safe for missing fields. */
export function recordTitle(entity, record) {
  try {
    return entity.title(record) || record.id || 'Untitled';
  } catch {
    return record?.id || 'Untitled';
  }
}
