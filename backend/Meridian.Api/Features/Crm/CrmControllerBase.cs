using System.ComponentModel.DataAnnotations;
using System.Text;
using Meridian.Api.Features.Users;
using Meridian.Api.Infrastructure.Supabase;
using Microsoft.AspNetCore.Authorization;
using Microsoft.AspNetCore.Mvc;

namespace Meridian.Api.Features.Crm;

public sealed class ListQuery
{
    /// <summary>Case-insensitive text search across the entity's search columns.</summary>
    [StringLength(100)] public string? Search { get; init; }

    /// <summary>Property to sort by (camelCase, e.g. "createdAt", "value"). Defaults to newest first.</summary>
    [StringLength(50)] public string? Sort { get; init; }

    [RegularExpression("^(?i)(asc|desc)$")] public string? Order { get; init; }

    [Range(1, CrmLimits.MaxPageSize)] public int Limit { get; init; } = CrmLimits.MaxPageSize;

    [Range(0, int.MaxValue)] public int Offset { get; init; }
}

public sealed class BatchRequest<T> where T : CrmRecord
{
    /// <summary>Records to create or overwrite (matched by id).</summary>
    [MaxLength(CrmLimits.MaxBatchSize)] public List<T> Upsert { get; init; } = [];

    /// <summary>Ids of records to delete.</summary>
    [MaxLength(CrmLimits.MaxBatchSize)] public List<string> Delete { get; init; } = [];
}

public sealed record BatchResult<T>(IReadOnlyList<T> Upserted, IReadOnlyList<string> Deleted);

public static class CrmLimits
{
    public const int MaxPageSize = 1000;
    public const int MaxBatchSize = 500;
}

/// <summary>
/// Standard REST surface shared by every CRM resource:
/// GET list · GET by id · POST create · PUT replace · DELETE · POST batch.
/// All calls run as the signed-in user, so Supabase RLS applies. Every action
/// needs an active profile; deleting needs a role in <see cref="AppRoles.CanDeleteRecords"/>.
/// </summary>
[ApiController]
[Authorize]
[RequireRole]
[Produces("application/json")]
public abstract class CrmControllerBase<T>(SupabaseRestClient db) : ControllerBase where T : CrmRecord
{
    public const string TotalCountHeader = "X-Total-Count";

    /// <summary>Supabase table name.</summary>
    protected abstract string Table { get; }

    /// <summary>Prefix for ids generated by the server, e.g. "lead".</summary>
    protected abstract string IdPrefix { get; }

    /// <summary>Columns matched by <see cref="ListQuery.Search"/>.</summary>
    protected abstract IReadOnlyList<string> SearchColumns { get; }

    /// <summary>Exact-match filters: query-string name → column, e.g. status → status.</summary>
    protected abstract IReadOnlyDictionary<string, string> FilterColumns { get; }

    /// <summary>Sortable fields: camelCase API name → column.</summary>
    protected abstract IReadOnlyDictionary<string, string> SortColumns { get; }

    [HttpGet]
    public async Task<ActionResult<IReadOnlyList<T>>> List([FromQuery] ListQuery query, CancellationToken ct)
    {
        var result = await db.ListAsync<T>(Table, BuildListQuery(query), ct);
        Response.Headers[TotalCountHeader] = result.Total.ToString();
        return Ok(result.Items);
    }

    [HttpGet("{id}")]
    public async Task<ActionResult<T>> Get(string id, CancellationToken ct)
    {
        var record = await db.GetAsync<T>(Table, id, ct);
        return record is null ? NotFoundProblem(id) : Ok(record);
    }

    [HttpPost]
    public async Task<ActionResult<T>> Create(T record, CancellationToken ct)
    {
        record.Id ??= NewId();
        record.ClearServerManagedFields();
        var created = await db.InsertAsync(Table, record, ct);
        return CreatedAtAction(nameof(Get), new { id = created.Id }, created);
    }

    [HttpPut("{id}")]
    public async Task<ActionResult<T>> Update(string id, T record, CancellationToken ct)
    {
        if (record.Id is not null && record.Id != id)
            return ValidationProblem(Field("id", "The id in the body does not match the id in the URL."));

        record.Id = id;
        record.ClearServerManagedFields();
        var updated = await db.UpdateAsync(Table, id, record, ct);
        return updated is null ? NotFoundProblem(id) : Ok(updated);
    }

    [HttpDelete("{id}")]
    [RequireRole(AppRoles.Admin, AppRoles.Ceo, AppRoles.Manager)]
    [ProducesResponseType(StatusCodes.Status204NoContent)]
    public async Task<IActionResult> Delete(string id, CancellationToken ct)
    {
        var deleted = await db.DeleteAsync(Table, [id], ct);
        return deleted.Count == 0 ? NotFoundProblem(id) : NoContent();
    }

    /// <summary>Applies many creates/updates and deletes in one round trip (used by imports and bulk edits).</summary>
    [HttpPost("batch")]
    public async Task<ActionResult<BatchResult<T>>> Batch(BatchRequest<T> request, CancellationToken ct)
    {
        var deleteIds = request.Delete.Where(id => !string.IsNullOrWhiteSpace(id)).Select(id => id.Trim()).Distinct().ToList();
        if (deleteIds.Count > 0)
        {
            var role = await HttpContext.RequestServices.GetRequiredService<CurrentUser>().RoleAsync(ct);
            if (!AppRoles.CanDeleteRecords.Contains(role))
                return RequireRoleFilter.Forbidden($"Your role ({role ?? "none"}) is not allowed to delete records.", "forbidden_role");
        }
        foreach (var record in request.Upsert)
        {
            record.Id ??= NewId();
            record.ClearServerManagedFields();
        }

        var duplicate = request.Upsert.GroupBy(r => r.Id).FirstOrDefault(g => g.Count() > 1)?.Key;
        if (duplicate is not null)
            return ValidationProblem(Field("upsert", $"Record '{duplicate}' appears more than once."));
        var conflicting = request.Upsert.Select(r => r.Id!).Intersect(deleteIds).FirstOrDefault();
        if (conflicting is not null)
            return ValidationProblem(Field("delete", $"Record '{conflicting}' cannot be both saved and deleted."));

        var upserted = await db.UpsertAsync(Table, request.Upsert, ct);
        var deleted = await db.DeleteAsync(Table, deleteIds, ct);
        return Ok(new BatchResult<T>(upserted, deleted));
    }

    private string BuildListQuery(ListQuery query)
    {
        var sb = new StringBuilder("select=*");

        foreach (var (param, column) in FilterColumns)
        {
            var value = Request.Query[param].ToString();
            if (!string.IsNullOrWhiteSpace(value)) sb.Append($"&{column}=eq.{SupabaseRestClient.Escape(value.Trim())}");
        }

        var term = SanitizeSearch(query.Search);
        if (term.Length > 0 && SearchColumns.Count > 0)
        {
            var pattern = SupabaseRestClient.Escape($"*{term}*");
            sb.Append("&or=(").Append(string.Join(',', SearchColumns.Select(c => $"{c}.ilike.{pattern}"))).Append(')');
        }

        var direction = string.Equals(query.Order, "asc", StringComparison.OrdinalIgnoreCase) ? "asc" : "desc";
        var sortColumn = query.Sort is not null && SortColumns.TryGetValue(query.Sort, out var col) ? col : "created_at";
        sb.Append($"&order={sortColumn}.{direction}.nullslast,id.asc");
        sb.Append($"&limit={query.Limit}&offset={query.Offset}");
        return sb.ToString();
    }

    // PostgREST uses , ( ) and * as syntax inside or=(…); strip them from user input.
    private static string SanitizeSearch(string? search) =>
        new string((search ?? string.Empty).Where(c => c is not (',' or '(' or ')' or '*' or '"' or '\\' or ':')).ToArray()).Trim();

    private string NewId() => $"{IdPrefix}-{Guid.NewGuid():N}";

    private ActionResult NotFoundProblem(string id) =>
        Problem(statusCode: StatusCodes.Status404NotFound, title: $"No record with id '{id}' was found.");

    private static Microsoft.AspNetCore.Mvc.ModelBinding.ModelStateDictionary Field(string key, string message)
    {
        var state = new Microsoft.AspNetCore.Mvc.ModelBinding.ModelStateDictionary();
        state.AddModelError(key, message);
        return state;
    }
}
